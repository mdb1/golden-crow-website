interface FamilySpec {
  baseEn: string;
  baseEs: string;
  equipments: EquipmentKey[];
  aliases: string[];
  overview: string;
  bodyPart: StandardBodyPart;
  muscleGroups: MuscleGroup[];
  targetMuscles: string[];
  secondaryMuscles: string[];
  variations?: string[];
  /**
   * How the exercise is logged. Defaults to "reps". Set "time" for static holds
   * (stretches) and timed warm-ups that are logged by duration_seconds. Mirrors
   * the `metric` field consumed by exercise-schema.ts and the iOS/Android apps
   * (Phase 26). See issue #307.
   */
  metric?: "reps" | "time";
}

export interface StandardLibraryExercise {
  exerciseId: string;
  name: { en: string; es: string };
  bodyParts: StandardBodyPart[];
  equipment: EquipmentKey[];
  targetMuscles: string[];
  secondaryMuscles: string[];
  keywords: string[];
  variations: string[];
  overview: string;
  tags: string[];
  muscleGroups: MuscleGroup[];
  metric: "reps" | "time";
}

function slugify(value: string): string {
  return value
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function uniq(values: string[]): string[] {
  return Array.from(new Set(values.map((value) => value.trim()).filter(Boolean)));
}

function makeKeywords(baseEn: string, baseEs: string, equipment: EquipmentKey, aliases: string[]): string[] {
  const equipmentEn = EQUIPMENT_LABELS[equipment].en;
  const equipmentEs = EQUIPMENT_LABELS[equipment].es;
  return uniq([
    baseEn,
    baseEs,
    `${baseEn} ${equipmentEn}`,
    `${equipmentEn} ${baseEn}`,
    `${baseEs} ${equipmentEs}`,
    `${equipmentEs} ${baseEs}`,
    ...aliases,
  ]);
}

function makeExercise(groupSlug: string, family: FamilySpec, equipment: EquipmentKey): StandardLibraryExercise {
  const equipmentEn = EQUIPMENT_LABELS[equipment].en;
  const equipmentEs = EQUIPMENT_LABELS[equipment].es;
  const nameEn = `${family.baseEn} (${equipmentEn})`;
  const nameEs = `${family.baseEs} (${equipmentEs})`;
  return {
    exerciseId: `std-${groupSlug}-${slugify(family.baseEn)}-${slugify(equipmentEn)}`,
    name: { en: nameEn, es: nameEs },
    bodyParts: [family.bodyPart],
    equipment: [equipment],
    targetMuscles: family.targetMuscles,
    secondaryMuscles: family.secondaryMuscles,
    keywords: makeKeywords(family.baseEn, family.baseEs, equipment, family.aliases),
    variations: family.variations ?? [],
    overview: family.overview,
    tags: [STANDARD_LIBRARY_TAG],
    muscleGroups: family.muscleGroups,
    metric: family.metric ?? "reps",
  };
}

function family(input: FamilySpec): FamilySpec {
  return input;
}


function buildGroupExercises(spec: { slug: string; families: FamilySpec[] }): StandardLibraryExercise[] {
  return spec.families.flatMap((family) =>
    family.equipments.map((equipment) => makeExercise(spec.slug, family, equipment)),
  );
}

export const STANDARD_LIBRARY_EXERCISES: StandardLibraryExercise[] = GROUPS.flatMap(buildGroupExercises);

export function standardLibraryPreviewTitle(item: StandardLibraryExercise): string {
  return item.name.en;
}

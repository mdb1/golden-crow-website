import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const OBJECT_TYPES = [
  "pgo_form",
  "pgo_bundle_of_symptoms",
  "pgo_bundle_of_candidate_genes",
  "pgo_informed_consent",
  "pgo_test_order",
  "pgo_collection_request",
  "pgo_blood_sample",
  "pgo_tissue_sample",
  "pgo_embryo_sample",
  "pgo_dna_sample",
  "pgo_sequence_reads",
  "pgo_sequence_data",
  "pgo_aligned_reads",
  "pgo_unannotated_vcf",
  "pgo_annotated_vcf",
  "pgo_interactive_report",
  "pgo_pdf_report",
  "pgo_image_bundle",
  "pgo_karyotype_result",
  "pgo_flow_cytometry_data",
];

const FORBIDDEN_CONTENT_KEYS = new Set([
  "object_id",
  "object_type",
  "schema_version",
  "revision",
  "created_at",
  "created_by",
  "input_refs",
  "files",
  "data",
]);

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sourceDirectory = path.resolve(
  scriptDirectory,
  "../../Pocket-Genes-Catalog-Wiki/schemas/objects",
);
const targetPath = path.resolve(
  scriptDirectory,
  "../src/contracts/pgo-object-schemas.generated.ts",
);

const schemas = {};
for (const objectType of OBJECT_TYPES) {
  const sourcePath = path.join(sourceDirectory, `${objectType}.schema.json`);
  const schema = JSON.parse(await readFile(sourcePath, "utf8"));
  if (
    schema?.type !== "object" ||
    !schema.properties ||
    typeof schema.properties !== "object" ||
    schema.additionalProperties !== false
  ) {
    throw new Error(
      `${sourcePath} must declare a closed root object content schema for ${objectType}.`,
    );
  }
  const forbiddenKey = Object.keys(schema.properties).find((key) =>
    FORBIDDEN_CONTENT_KEYS.has(key),
  );
  if (forbiddenKey) {
    throw new Error(
      `${sourcePath} declares legacy envelope key ${forbiddenKey} inside PGO content.`,
    );
  }
  if (
    schema.properties.notes?.type !== "string" ||
    schema.required?.includes("notes")
  ) {
    throw new Error(
      `${sourcePath} must declare notes as an optional root string.`,
    );
  }
  delete schema.$id;
  delete schema.$schema;
  schemas[objectType] = schema;
}

const output = `// Generated by scripts/generate-pgo-object-schemas.mjs.
// Source: Pocket-Genes-Catalog-Wiki/schemas/objects/*.schema.json
// Do not edit this file by hand.

export const PGO_OBJECT_SCHEMAS: Readonly<
  Record<string, Record<string, unknown>>
> = ${JSON.stringify(schemas, null, 2)};
`;

await mkdir(path.dirname(targetPath), { recursive: true });
await writeFile(targetPath, output, "utf8");

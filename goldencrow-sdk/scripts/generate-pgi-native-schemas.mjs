import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const NATIVE_MODELS = {
  mdm: "pgi1-mdm.schema.json",
  ag: "pgi2-ag.schema.json",
  "2pq": "pgi3-2pq.schema.json",
};

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const sourceDirectory = path.resolve(
  scriptDirectory,
  "../../Pocket-Genes-Catalog-Wiki/schemas/protocol",
);
const targetPath = path.resolve(
  scriptDirectory,
  "../src/contracts/pgi-native-schemas.generated.ts",
);

const schemas = {};
for (const [model, fileName] of Object.entries(NATIVE_MODELS)) {
  const sourcePath = path.join(sourceDirectory, fileName);
  const schema = JSON.parse(await readFile(sourcePath, "utf8"));
  const rootDefinitionName = schema?.$ref?.match(/^#\/\$defs\/(.+)$/)?.[1];
  const rootDefinition = rootDefinitionName
    ? schema?.$defs?.[rootDefinitionName]
    : undefined;

  if (
    !rootDefinitionName ||
    rootDefinition?.type !== "object" ||
    !rootDefinition.properties ||
    !Array.isArray(rootDefinition.required) ||
    rootDefinition.additionalProperties !== false
  ) {
    throw new Error(
      `${sourcePath} must reference a closed, required-field native root object.`,
    );
  }

  delete schema.$id;
  delete schema.$schema;
  schemas[model] = schema;
}

const output = `// Generated by scripts/generate-pgi-native-schemas.mjs.
// Source: Pocket-Genes-Catalog-Wiki/schemas/protocol/pgi*.schema.json
// Do not edit this file by hand.

export const PGI_NATIVE_SCHEMAS = ${JSON.stringify(schemas, null, 2)} as const;
`;

await mkdir(path.dirname(targetPath), { recursive: true });
await writeFile(targetPath, output, "utf8");
